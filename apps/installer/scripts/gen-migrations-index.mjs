// Writes src/db/migrations/index.ts from drizzle-kit's journal, with each
// migration's SQL inlined as a string, so the Worker bundle (wrangler) and the
// tests (Vitest) need no loader for .sql files. Run by `pnpm db:generate`
// after `drizzle-kit generate`; a test fails if the index and the files
// disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/db/migrations");
const journal = JSON.parse(readFileSync(join(dir, "meta/_journal.json"), "utf8"));
const entries = [...journal.entries].sort((a, b) => a.idx - b.idx);

const lines = [
  "// Generated by scripts/gen-migrations-index.mjs from meta/_journal.json. Do not edit.",
  "",
  "/** Every migration in apply order; the n-th is recorded as version n + 1. */",
  "export const migrations: readonly { tag: string; sql: string }[] = [",
  // The shape Biome formats it to, so a regenerated file passes `biome check`.
  ...entries.flatMap((e) => [
    "  {",
    `    tag: ${JSON.stringify(e.tag)},`,
    `    sql: ${JSON.stringify(readFileSync(join(dir, `${e.tag}.sql`), "utf8"))},`,
    "  },",
  ]),
  "];",
  "",
];
writeFileSync(join(dir, "index.ts"), lines.join("\n"));
console.log(`wrote src/db/migrations/index.ts (${entries.length} migrations)`);
