// Writes src/db/migrations/index.ts from drizzle-kit's journal so the Worker bundle
// carries every migration as a string (Vite `?raw` imports), in journal order.
// Run by `pnpm db:generate` after `drizzle-kit generate`; a test fails if the
// index and the journal disagree.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "../src/db/migrations");
const journal = JSON.parse(readFileSync(join(dir, "meta/_journal.json"), "utf8"));
const entries = [...journal.entries].sort((a, b) => a.idx - b.idx);

const lines = [
  "// Generated by scripts/gen-migrations-index.mjs from meta/_journal.json. Do not edit.",
  "",
  ...entries.map((e) => `import m${String(e.idx).padStart(4, "0")} from "./${e.tag}.sql?raw";`),
  "",
  "/** Every migration in apply order. `schema_version` counts how many have been applied. */",
  "export const migrations: readonly { tag: string; sql: string }[] = [",
  ...entries.map((e) => `  { tag: "${e.tag}", sql: m${String(e.idx).padStart(4, "0")} },`),
  "];",
  "",
];
writeFileSync(join(dir, "index.ts"), lines.join("\n"));
console.log(`wrote src/db/migrations/index.ts (${entries.length} migrations)`);
