// Regenerates src/spdx-ids.ts from the SPDX License List data
// (https://github.com/spdx/license-list-data). Run it when SPDX publishes a
// new list:
//   pnpm --filter @appflare/schema update-spdx-ids
// It downloads licenses.json and exceptions.json from the list's main branch,
// or reads them from a directory given as the first argument.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const BASE = "https://raw.githubusercontent.com/spdx/license-list-data/main/json";

async function load(name) {
  const dir = process.argv[2];
  if (dir !== undefined) return JSON.parse(readFileSync(join(dir, name), "utf8"));
  const response = await fetch(`${BASE}/${name}`);
  if (!response.ok) throw new Error(`${name}: HTTP ${response.status}`);
  return response.json();
}

const licenses = await load("licenses.json");
const exceptions = await load("exceptions.json");

const sorted = (ids) => [...ids].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const current = sorted(
  licenses.licenses.filter((l) => !l.isDeprecatedLicenseId).map((l) => l.licenseId),
);
const deprecated = sorted(
  licenses.licenses.filter((l) => l.isDeprecatedLicenseId).map((l) => l.licenseId),
);
const exceptionIds = sorted(
  exceptions.exceptions.filter((e) => !e.isDeprecatedLicenseId).map((e) => e.licenseExceptionId),
);

/** Wraps space-separated ids into string literal lines of at most ~90 characters. */
function wrapped(ids) {
  const lines = [];
  let line = "";
  for (const id of ids) {
    if (line.length > 0 && line.length + id.length + 1 > 88) {
      lines.push(line);
      line = "";
    }
    line += (line.length > 0 ? " " : "") + id;
  }
  if (line.length > 0) lines.push(line);
  return lines
    .map((l, i) => `  ${JSON.stringify(i < lines.length - 1 ? `${l} ` : l)}`)
    .join(" +\n");
}

const out = `// Generated by scripts/update-spdx-ids.mjs from the SPDX License List
// ${licenses.licenseListVersion} (${licenses.releaseDate.slice(0, 10)}); do not edit by hand.

/** The version of the SPDX License List these ids come from. */
export const SPDX_LICENSE_LIST_VERSION = ${JSON.stringify(licenses.licenseListVersion)};

/** Every current SPDX license id, space-separated. */
export const SPDX_LICENSE_IDS_TEXT =
${wrapped(current)};

/** Every deprecated SPDX license id, space-separated. */
export const SPDX_DEPRECATED_LICENSE_IDS_TEXT =
${wrapped(deprecated)};

/** Every current SPDX license exception id, space-separated. */
export const SPDX_EXCEPTION_IDS_TEXT =
${wrapped(exceptionIds)};
`;

const here = dirname(fileURLToPath(import.meta.url));
const target = join(here, "..", "src", "spdx-ids.ts");
writeFileSync(target, out);
console.log(
  `Wrote ${target}: ${current.length} licenses, ${deprecated.length} deprecated, ${exceptionIds.length} exceptions (SPDX ${licenses.licenseListVersion})`,
);
